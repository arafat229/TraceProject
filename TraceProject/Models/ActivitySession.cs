namespace TraceProject.Models;

public enum ActivityState
{
    /// <summary>Keyboard or mouse input within the idle threshold.</summary>
    Active = 0,
    /// <summary>Unlocked but no input for longer than the idle threshold.</summary>
    Idle = 1,
    /// <summary>Windows session locked.</summary>
    Locked = 2,
    /// <summary>The agent stopped reporting (shut down, asleep, off the network). Live status only, never a session.</summary>
    Offline = 3,
}

/// <summary>
/// One continuous interval on a device with a single state and foreground window.
/// The agent sends the open session repeatedly with a growing EndedAt, so rows are
/// upserted by (DeviceId, ClientId) and retries never create duplicates.
/// </summary>
public class ActivitySession
{
    public long Id { get; set; }
    public long DeviceId { get; set; }
    public Device Device { get; set; } = null!;
    public long EmployeeId { get; set; }

    /// <summary>Generated by the agent; makes uploads idempotent.</summary>
    public Guid ClientId { get; set; }

    /// <summary>Server-local date of StartedAt (see Services/WorkDay.cs).</summary>
    public DateOnly WorkDate { get; set; }

    public ActivityState State { get; set; }
    public string? AppName { get; set; }
    public string? WindowTitle { get; set; }
    public DateTime StartedAt { get; set; }
    public DateTime EndedAt { get; set; }
}
