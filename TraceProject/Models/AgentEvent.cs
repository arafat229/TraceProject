namespace TraceProject.Models;

public enum AgentEventKind
{
    /// <summary>TraceAgent started (sign-in or launched by hand).</summary>
    Started = 0,
    /// <summary>The employee closed TraceAgent from its tray menu.</summary>
    UserExit = 1,
    /// <summary>Windows is shutting down or the user is signing out.</summary>
    Shutdown = 2,
    /// <summary>The computer went to sleep or hibernation.</summary>
    Sleep = 3,
    /// <summary>The computer woke up.</summary>
    Resumed = 4,
    /// <summary>Server side: the agent stopped reporting without saying why (killed, crashed, network gone).</summary>
    ConnectionLost = 10,
}

/// <summary>
/// Agent lifecycle history: when monitoring started and stopped, and why. Agent events are
/// queued and sent like sessions, so an exit that could not be sent arrives on the next start.
/// </summary>
public class AgentEvent
{
    public long Id { get; set; }
    public long DeviceId { get; set; }
    public Device Device { get; set; } = null!;
    public long EmployeeId { get; set; }

    /// <summary>Generated by the agent (makes uploads idempotent); null for server-side events.</summary>
    public Guid? ClientId { get; set; }

    public AgentEventKind Kind { get; set; }
    public DateTime At { get; set; }

    /// <summary>Server-local date of At (see Services/WorkDay.cs).</summary>
    public DateOnly WorkDate { get; set; }
}
